import { betterAuth } from "better-auth";
import { prismaAdapter } from "better-auth/adapters/prisma";
import { admin, anonymous, organization } from "better-auth/plugins";
import type { Env } from "../../config/env.js";
import type { PrismaClient } from "../../lib/prisma.js";
import type { ProvisioningService } from "./provisioning.service.js";

export interface AuthDependencies {
  prisma: PrismaClient;
  env: Env;
  provisioning: ProvisioningService;
}

export function createAuth({ prisma, env, provisioning }: AuthDependencies) {
  const googleEnabled = Boolean(env.GOOGLE_CLIENT_ID && env.GOOGLE_CLIENT_SECRET);

  return betterAuth({
    appName: "MyBricks",
    baseURL: env.BETTER_AUTH_URL,
    secret: env.BETTER_AUTH_SECRET,
    trustedOrigins: [env.FRONTEND_URL],

    database: prismaAdapter(prisma, { provider: "postgresql" }),
    // Ids are generated by the database (gen_random_uuid()).
    advanced: { database: { generateId: false } },

    emailAndPassword: { enabled: true, minPasswordLength: 8 },
    socialProviders: googleEnabled
      ? { google: { clientId: env.GOOGLE_CLIENT_ID!, clientSecret: env.GOOGLE_CLIENT_SECRET! } }
      : {},

    plugins: [
      organization({
        creatorRole: "owner",
        // No e-mail provider yet: invitations are shared as a link built from the invitation id,
        // returned by the create-invitation endpoint. This callback intentionally sends nothing.
        async sendInvitationEmail() {},
        // Invitation ids are random UUIDs and e-mail verification is not available yet.
        requireEmailVerificationOnInvitation: false,
        schema: {
          organization: {
            additionalFields: {
              isDemo: { type: "boolean", required: false, input: false },
              demoExpiresAt: { type: "date", required: false, input: false },
            },
          },
        },
      }),
      admin(),
      anonymous({
        onLinkAccount: async ({ anonymousUser, newUser }) => {
          await provisioning.adoptDemoWorkspace(anonymousUser.user.id, {
            id: newUser.user.id,
            name: newUser.user.name,
          });
        },
      }),
    ],

    databaseHooks: {
      user: {
        create: {
          after: async (user) => {
            await provisioning.provisionForNewUser({
              id: user.id,
              name: user.name,
              isAnonymous: Boolean((user as { isAnonymous?: boolean | null }).isAnonymous),
            });
          },
        },
      },
      session: {
        create: {
          before: async (session) => {
            const organizationId = await provisioning.initialOrganizationId(session.userId);
            return { data: { ...session, activeOrganizationId: organizationId ?? undefined } };
          },
        },
      },
    },
  });
}

export type Auth = ReturnType<typeof createAuth>;
